"""
================================================================================
 TOOLS/MAKE_DEMO_BRAIN.PY — Демонстрационный мозг для публичной страницы
================================================================================
Прогоняет заранее написанный разговор через НАСТОЯЩИЙ BrainSession и
складывает результат в файл. Из этого файла `render_memory.py` рисует
страницу, которую не стыдно выложить наружу.

ЗАЧЕМ ОТДЕЛЬНЫЙ ИНСТРУМЕНТ, А НЕ ЧУЖАЯ БАЗА. В `storage/brains` лежат
базы живых людей, разговаривавших с ботом. Выложить снимок такой базы —
значит опубликовать чужую личную переписку: адрес рано или поздно
утечёт, а восстановить по графу, кто и о чём говорил, тривиально.
Публичная страница обязана строиться на ВЫМЫШЛЕННОМ разговоре, и других
вариантов здесь нет.

Разговор ниже написан руками. Он нарочно смешан: содержательные факты
вперемешку с трёпом, одна поправка, несколько возвращений к старой теме.
Ровно на этой смеси и видно, что память делает выбор, а не пишет подряд.

Сеть не нужна: ответы даёт заглушка, та же, что в тестах и стендах.

Запуск:
    python tools/make_demo_brain.py -o docs/demo_brain.db
================================================================================
"""

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
sys.path.insert(0, "tools")

os.environ.setdefault("LOG_LEVEL", "ERROR")

# Разговор за несколько недель. Реплики пользователя; ответы придумывает
# заглушка, они в снимке не важны.
CONVERSATION = [
    "привет, давай знакомиться",
    "меня зовут Паша, я бэкенд-разработчик",
    "работаю в финтехе, пишу на питоне",
    "спасибо",
    "у меня аллергия на пенициллин, это важно",
    "ок",
    "сестру зовут Мира",
    "как дела",
    "Мира разводит спаниелей",
    "погода сегодня нормальная",
    "лечу в Стамбул двадцатого мая",
    "ага",
    "ничего нового",
    "я не ем мясо уже три года",
    "понял",
    "привет",
    "кстати рейс перенесли на двадцать второе",
    "спасибо большое",
    "что нового",
    "Мира ещё реставрирует пианино",
    "ясно",
    "напомни, когда у меня рейс",
    "точно",
    "а что там с аллергией",
    "хорошо",
    "погода опять та же",
    "до связи",
    "привет снова",
    "какие у меня планы на май",
    "спасибо",
    "родители живут в Новосибирске",
    "понятно",
    "в Новосибирске зимой доходит до сорока",
    "ничего себе",
    "ладно, пока",
]


def main() -> None:
    parser = argparse.ArgumentParser(description="Собрать демонстрационный мозг")
    parser.add_argument("-o", "--output", default="docs/demo_brain.db")
    args = parser.parse_args()

    from simulate_learning import install_llm_stub

    install_llm_stub()
    from core.brain_session import BrainSession, ManualWallClock

    path = Path(args.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists():
        path.unlink()

    # Время фиксированное, иначе два прогона дают разные снимки при том же
    # разговоре — эпоха мозга входит в каждую метку в базе.
    wall = ManualWallClock(start=1_700_000_000.0, seconds_per_call=0.0)
    session = BrainSession(db_path=str(path), wall_clock=wall)

    for index, message in enumerate(CONVERSATION, start=1):
        session.process_message(message)
        # Полчаса между репликами, сутки между «днями» по десять реплик.
        wall.advance(1800.0 if index % 10 else 86400.0)

    print(f"  разговор из {len(CONVERSATION)} реплик прогнан")
    print(f"  мозг: {path}")


if __name__ == "__main__":
    main()
