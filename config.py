# ==========================================================================
# 17a. SURPRISE — СОБСТВЕННОЕ удивление организма (ошибка предсказания)
# ==========================================================================
# Спайк-память — сердце системы: «записываем только то, что удивило».
# Раньше «удивление» считалось энтропией Шеннона по символам строки, то
# есть было свойством ТЕКСТА, а не отношением ОРГАНИЗМА к тексту. Замер
# показывал, что новорождённый мозг и мозг, слышавший фразу 50 раз, дают
# ровно одно и то же число (0.856), а бессмысленный набор букв почти
# неотличим от осмысленной фразы. Главный порог системы был слеп к опыту.
#
# Теперь удивление считается по СОБСТВЕННОМУ графу организма (см.
# MemoryGraph.compute_surprise) из двух составляющих:
#   - лексическая новизна   — насколько знакомы сами слова (word-узлы);
#   - структурная новизна   — насколько привычны сочетания соседних слов
#                             (рёбра со-встречаемости).
#
# Пропорция 0.6/0.4 повторяет уже принятую в проекте развесовку
# MEMORY_KEYWORD_WEIGHT/MEMORY_FUZZY_WEIGHT: знание самих единиц весит
# больше, чем знание их сочетаний.
# При скольких содержательных словах реплика способна удивить в полную
# силу. Короче — удивление режется пропорционально: одно незнакомое слово
# несёт меньше информации, чем шесть. Без этой поправки "ага" и "моя дочь
# Лиза ей шесть лет" на пустой памяти давали одинаковые 1.000, и память
# засорялась междометиями с первого дня.
# Пол угасания: до какого веса опускается узел с полностью заслуженным
# одобрением. Подкреплённое тускнеет, но не исчезает — иначе отмеченное
# важным, но ни разу не пригодившееся, уходило в ноль вместе с рутиной.
MEMORY_FLOOR_MAX = _get_float("MEMORY_FLOOR_MAX", 0.25)

SURPRISE_FULL_CONTENT_TOKENS = _get_int("SURPRISE_FULL_CONTENT_TOKENS", 2)

SURPRISE_LEXICAL_WEIGHT = _get_float("SURPRISE_LEXICAL_WEIGHT", 0.6)
SURPRISE_STRUCTURAL_WEIGHT = _get_float("SURPRISE_STRUCTURAL_WEIGHT", 0.4)





# ==========================================================================
# 17b. SPEECH STAGE GATING — стадии речевого развития (continuous, с зоной смешения)
# ==========================================================================
# Порог веса word-узла, начиная с которого слово считается ЗАКРЕПЛЁННЫМ
# ("усвоенным"), а не просто разово услышанным. Новый word-узел создаётся
# с весом WORD_NODE_INITIAL_WEIGHT (0.12) и растёт на WORD_NODE_REINFORCE_STEP
# (0.04) при каждом повторном появлении слова — порог 0.20 соответствует
# ~3 употреблениям слова пользователем. Используется в
# MemoryGraph.get_vocabulary_size() для гейтинга речевых стадий: без этого
# порога слово, услышанное один раз, немедленно засчитывалось бы в
# vocabulary_size, хотя реального освоения языка ещё не произошло.
#
# 0.18, а НЕ 0.20 — порог обязан стоять МЕЖДУ ступенями лестницы
# подкрепления (0.12 -> 0.16 -> 0.20), а не ровно на ступени. При 0.20
# слово после третьего повторения попадало точно на порог и слетало со
# статуса освоенного от ЛЮБОГО угасания: уже через пару часов паузы
# vocabulary_size проваливался обратно. Требуемое число повторений (три)
# при этом не изменилось — 0.16 < 0.18 <= 0.20, — зато у освоенного слова
# появился запас, которого хватает на месяцы молчания.
VOCABULARY_MASTERY_MIN_WEIGHT = _get_float("VOCABULARY_MASTERY_MIN_WEIGHT", 0.18)
# --------------------------------------------------------------------------
# Пороги стадий откалиброваны под РЕАЛЬНЫЙ канал ввода — сообщения мессенджера
# по ~7 слов, а не под корпус текстов. Замер стендом tools/simulate_learning.py
# (режим «20 сообщений вечером + ночная пауза», 30% редких слов):
#     порог 50 -> первая связная фраза на 64-м сообщении
#     порог 35 -> на 49-м
#     порог 25 -> на 33-м   <- выбрано: примерно один вечер общения
# Прежние 50/300/800 означали ~64 сообщения ЧИСТОГО лепета в ответ, до
# которых ни один живой человек не дотерпливал (см. storage/brains/*.db).
#
# ВАЖНО: измерен только порог Stage 0 — словарь в стенде упирается в потолок
# корпуса (~170 слов), поэтому границы Stage 1/2 пересчитаны пропорционально
# (÷2) и ждут калибровки на живых данных.
# --------------------------------------------------------------------------
# Stage 0 (довербальный): vocab < SPEECH_STAGE_0_MAX_VOCAB -> только лепет/эхолалия,
# LLM и поиск по LTM не запускаются вообще.
SPEECH_STAGE_0_MAX_VOCAB = _get_int(
    "SPEECH_STAGE_0_MAX_VOCAB", 14 if SPEECH_DEMO_PACE else 25
)
# Stage 1 (раннее детство/телеграфная речь): vocab < SPEECH_STAGE_1_MAX_VOCAB ->
# LLM разрешена, но только ОДНО простое предложение, без абстракций.
SPEECH_STAGE_1_MAX_VOCAB = _get_int("SPEECH_STAGE_1_MAX_VOCAB", 150)
# Stage 2 (простая грамматика): vocab < SPEECH_STAGE_2_MAX_VOCAB -> разрешено
# 1-2 предложения и простые связки, но БЕЗ метафор/абстракций/сложных
# причинно-следственных объяснений — промежуточная ступень между
# "телеграфной" речью и полностью свободной.
SPEECH_STAGE_2_MAX_VOCAB = _get_int("SPEECH_STAGE_2_MAX_VOCAB", 400)
# Stage 3 (свободная речь): vocab >= SPEECH_STAGE_2_MAX_VOCAB -> обычные ограничения.
# Ширина зоны смешения вокруг каждой границы (в узлах словаря). Внутри этой
# зоны переход происходит ВЕРОЯТНОСТНО (линейно растущий шанс), а не резко.
SPEECH_STAGE_BLEND_WIDTH = _get_int(
    "SPEECH_STAGE_BLEND_WIDTH", 6 if SPEECH_DEMO_PACE else 15
)

# ==========================================================================
# 18. RETROSPECTIVE CORRECTION — устойчивость к сарказму и ложной похвале
# ==========================================================================
# Проблема: detect_feedback_valence — однократный, "слепой" маркерный
# анализ. Если пользователь сначала (сарказм) похвалил ошибочный ответ, а
# через реплику-две ОПРОВЕРГ сам себя ("не, стой, это неправильно") — без
# этого механизма ложное подкрепление остаётся навечно висеть на узле LTM.
#
# Retrospective Correction хранит короткую историю последних связок
# Input->Action->Feedback и, если новый фидбэк противоречит по знаку
# уже применённому ранее (в пределах окна) — откатывает и перекрывает
# прежний эффект, а также снижает "доверие" к конкретным маркерам,
# которые привели к ложному срабатыванию (Amygdala.marker_trust).
RETROSPECTIVE_CORRECTION_ENABLED = _get_str("RETROSPECTIVE_CORRECTION_ENABLED", "true").lower() == "true"

# Сколько последних связок Input->Action->Feedback хранится в истории
# (глубина "окна", в пределах которого возможна отложенная коррекция)
RETROSPECTIVE_WINDOW_SIZE = _get_int("RETROSPECTIVE_WINDOW_SIZE", 4)

# Максимальная дистанция во времени (виртуальные секунды brain_time),
# в пределах которой более позднее противоречащее сообщение считается
# ОПРОВЕРЖЕНИЕМ прошлой оценки, а не отдельным независимым фидбэком
RETROSPECTIVE_TIME_WINDOW_SECONDS = _get_float("RETROSPECTIVE_TIME_WINDOW_SECONDS", 180.0)

# Множитель силы "откат + перекрытие" при подтверждённой ложной оценке:
# итоговая коррекция = |исходная_дельта| * RETROSPECTIVE_REVERSAL_STRENGTH
# (> 1.0, т.к. подтверждённая ложная похвала/порицание — куда более
# сильный обучающий сигнал, чем обычный однократный фидбэк)
RETROSPECTIVE_REVERSAL_STRENGTH = _get_float("RETROSPECTIVE_REVERSAL_STRENGTH", 1.6)

# Нижняя граница "доверия" к отдельному маркеру одобрения/порицания
# (см. core/amygdala.py: Amygdala.marker_trust) — не даём доверию упасть
# до нуля, маркер по-прежнему что-то значит, просто гораздо слабее.
MARKER_TRUST_MIN = _get_float("MARKER_TRUST_MIN", 0.15)

# Шаг понижения доверия к маркеру при подтверждённом ложном срабатывании
# (сарказм / ошибочная похвала / порицание, вскрытые Retrospective Correction)
MARKER_TRUST_PENALTY_STEP = _get_float("MARKER_TRUST_PENALTY_STEP", 0.25)

# Шаг медленного пассивного восстановления доверия к маркеру при каждом
# его использовании, которое впоследствии НЕ было опровергнуто —
# постепенная "реабилитация" маркера, если он раз за разом оказывается верным
MARKER_TRUST_RECOVERY_STEP = _get_float("MARKER_TRUST_RECOVERY_STEP", 0.03)

# Создавать ли в LTM абстрактный concept-узел, фиксирующий сам факт
# обнаруженного противоречия (пользователь сначала похвалил/поругал,
# потом опроверг сам себя) — накопление структурного опыта о
# ненадёжности конкретных маркеров в конкретном контексте диалога.
RETROSPECTIVE_IRONY_NODE_ENABLED = _get_str("RETROSPECTIVE_IRONY_NODE_ENABLED", "true").lower() == "true"


