# ==========================================================================
# 2. SPIKE MEMORY — порог пластичности
# ==========================================================================
# Базовый порог "спайка": если эмоциональная плотность / perplexity
# входящего сигнала превышает этот порог — информация записывается в память.
# Меньше значение -> система более "впечатлительная" (запоминает почти всё).
# Больше значение -> система более "равнодушная" (запоминает только сильное).
#
# 0.45, а не прежние 0.65 — порог ПРИШЛОСЬ пересчитать вместе с переходом
# на собственное удивление (см. раздел 17a). Раньше perplexity считалась
# энтропией символов и для любого нормального текста ВСЕГДА держалась около
# 0.85-0.9; эта постоянно высокая величина молча удерживала total_density
# у порога 0.65. Как только удивление стало честным и начало падать по мере
# обучения (0.88 -> 0.26 за 120 сообщений), плотность провалилась, и замер
# показал НОЛЬ спайков за весь прогон — организм перестал формировать
# эпизодическую память вообще.
#
# Подобрано стендом tools/simulate_learning.py по форме кривой записи.
# ПЕРЕСЧИТАН ВТОРОЙ РАЗ — при слиянии осей возбуждения. Раньше механизм
# самозащиты был МЁРТВЫМ КОДОМ: стресс накапливался на +0.025 за сообщение
# при восстановлении -6.00 за тик, то есть мгновенно падал в ноль, и
# эффективный порог всегда равнялся базовому. Теперь возбуждение живое и
# реально поднимает порог (см. Mood.effective_plasticity_threshold), значит
# база должна быть ниже на величину типичного вклада возбуждения:
#     0.45 при живом возбуждении ->  6 эпизодов за прогон (слишком глухо)
#     0.40                       -> 10
#     0.35                       -> 15-16, 12 спайков в начале, затем 0
#     0.30                       -> 19-21 (избыточно впечатлителен)
# 0.35 + типичное возбуждение ~0.4 * 0.25 даёт те же ~0.45 эффективного
# порога, что были откалиброваны ранее, — но теперь нагрузка действительно
# модулирует запись, а не игнорируется.
BASE_PLASTICITY_THRESHOLD = _get_float("BASE_PLASTICITY_THRESHOLD", 0.35)

# Порог может динамически "плыть" в момент стресса (см. STRESS блок ниже).
# Здесь — насколько сильно порог поднимается при перегрузке (защитный эффект).
PLASTICITY_STRESS_MODIFIER = _get_float("PLASTICITY_STRESS_MODIFIER", 0.25)


# ==========================================================================
# 3. DECAY & TIME — забывание и старение памяти
# ==========================================================================
# Скорость забывания (decay rate). Используется в экспоненциальной кривой
# затухания веса узла памяти: weight(t) = weight_0 * exp(-DECAY_RATE * dt)
DECAY_RATE = _get_float("DECAY_RATE", 0.05)

# AGE_T0 — характерное "время жизни" ЭПИЗОДИЧЕСКОЙ памяти без обращения.
# Эффективная постоянная времени забывания = AGE_T0 / DECAY_RATE, то есть
# при 3600/0.05 узел-эпизод теряет половину веса примерно за 14 часов.
# Для разговорных эпизодов это осознанно агрессивно — "бытовой шум должен
# уходить быстро", в этом и состоит тезис проекта.
# ПЕРЕСЧИТАН при переходе на когерентные часы. Раньше паузы между
# сессиями продвигали brain_time примерно настенным темпом (часы просто
# прыгали на time.time() при перезагрузке), а внутри разговора — всемеро
# быстрее. Теперь шкала одна и ускорена в TIME_ACCELERATION раз ВЕЗДЕ,
# включая паузы, поэтому характерное время эпизода должно вырасти во
# столько же раз. Замер это подтвердил: предсказание 7x, и оно же дало
# ровно прежние 16 эпизодических узлов за прогон.
#     3600  (1ч внутр) ->  3 эпизода — осыпаются за ночь
#     10800 (3ч)       -> 12
#     25200 (7ч)       -> 16   <- как до перехода
#     50400 (14ч)      -> 16 (насыщение)
# 25200 внутренних секунд = ровно 1 час реального времени.
AGE_T0 = _get_float("AGE_T0", 25200.0)  # 7 внутренних часов = 1 реальный

# --------------------------------------------------------------------------
# LEXICAL_AGE_T0 — то же самое, но для СЛОВАРЯ (node_type 'word'/'syllable').
#
# Словарь — это инфраструктура, а не вчерашний разговор: слово "мама" не
# забывается со скоростью реплики о погоде. С единым AGE_T0=1час словарь
# физически не мог накапливаться: измерено стендом (tools/simulate_learning.py)
#     пауза  6ч -> освоенное слово 0.20 падает до 0.148 (ниже порога освоения)
#     пауза 28ч -> узел удаляется из БД полностью
# то есть бот забывал весь выученный язык за одну ночь, а за выходные —
# безвозвратно. В режиме "20 сообщений вечером + ночная пауза" словарь
# колебался 5->1, 13->3, 17->4 и не рос НИКОГДА.
#
# 30 суток дают потерю ~1.2% в неделю полного молчания: слово живёт месяцами,
# но всё же угасает, если к нему никогда не возвращаться — забывание
# сохранено, просто на верном масштабе времени.
# --------------------------------------------------------------------------
LEXICAL_AGE_T0 = _get_float("LEXICAL_AGE_T0", 30.0 * 24 * 3600.0)  # 30 суток

# --------------------------------------------------------------------------
# STABILITY — сопротивление узла забыванию (кривая Эббингауза + эффект
# распределённого повторения).
#
# У живой памяти два независимых параметра, а не один: СИЛА (насколько
# ярко помнится сейчас = weight) и СТАБИЛЬНОСТЬ (насколько медленно
# забывается = сопротивление времени). Раньше был только weight, поэтому
# все эпизоды старели по одной шкале AGE_T0=1час независимо от того,
# пригодились они хоть раз или нет: замер показывал 11 эпизодических
# узлов до ночной паузы и 1-2 после неё — не забывание, а амнезия.
#
# Теперь эффективное время жизни узла = AGE_T0 * stability, а сама
# стабильность растёт при КАЖДОМ вспоминании (touch_node). Смысл:
# случайный обмен репликами уходит за сутки, а то, к чему организм
# реально возвращался, живёт месяцами. Экономия памяти сохраняется —
# просто "важность" теперь определяется востребованностью, а не
# случайным всплеском пунктуации в момент записи.
# --------------------------------------------------------------------------
STABILITY_INITIAL = _get_float("STABILITY_INITIAL", 1.0)
# Во сколько раз растёт стабильность за одно вспоминание (мультипликативно —
# как в моделях распределённого повторения, а не линейно)
STABILITY_GROWTH_FACTOR = _get_float("STABILITY_GROWTH_FACTOR", 1.5)
# Потолок: 40 * 20ч ≈ месяц периода полураспада. Выше — уже практически
# вечная память, а вечной памяти у организма быть не должно.
STABILITY_MAX = _get_float("STABILITY_MAX", 40.0)

# Порог веса, ниже которого узел памяти считается "забытым" и может
# быть физически удалён из графа/БД во время цикла "сна" (sleep_cycle.py)
FORGET_THRESHOLD = _get_float("FORGET_THRESHOLD", 0.05)

# Как часто запускать цикл дефрагментации/забывания (в секундах)


# ==========================================================================
# 4. EMOTION COEFFICIENTS — коэффициенты эмоциональной плотности
# ==========================================================================
# Эти коэффициенты используются в core/amygdala.py для расчёта
# "эмоциональной температуры" входящего сообщения.

# Вес CAPS LOCK (доля капса в тексте увеличивает эмоц. плотность)
EMOTION_CAPS_WEIGHT = _get_float("EMOTION_CAPS_WEIGHT", 0.3)

# Вес восклицательных знаков ("!!!")
EMOTION_EXCLAMATION_WEIGHT = _get_float("EMOTION_EXCLAMATION_WEIGHT", 0.25)

# Вес вопросительных знаков ("???") — неопределённость/тревога
EMOTION_QUESTION_WEIGHT = _get_float("EMOTION_QUESTION_WEIGHT", 0.15)

# Вес повторяющихся символов ("нееееет", "чтоооо")
EMOTION_REPETITION_WEIGHT = _get_float("EMOTION_REPETITION_WEIGHT", 0.1)

# Вес эмодзи / эмотиконов
EMOTION_EMOJI_WEIGHT = _get_float("EMOTION_EMOJI_WEIGHT", 0.2)

# Базовое "затухание" эмоции — насколько быстро эмоц. накал спадает
# между сообщениями (0 = не спадает, 1 = мгновенно забывается)


# ==========================================================================
# 5. STRESS / SELF-PRESERVATION — защитный слой (instincts.py)
# ==========================================================================
# Порог накопленного стресса, после которого включается "самозащита"
# (снижение пластичности, эхолалия, консервативные ответы)
STRESS_OVERLOAD_THRESHOLD = _get_float("STRESS_OVERLOAD_THRESHOLD", 0.8)

# Скорость накопления стресса за один "тревожный" импульс

# Скорость восстановления (снижения) стресса со временем/шагами


# ==========================================================================
# 6. INSTINCTS LAYER — базовые параметры инстинктов
# ==========================================================================
# Вероятность включения "эхолалии" (простого повторения/мимикрии)
# при недостатке уверенности модели
ECHOLALIA_PROBABILITY = _get_float("ECHOLALIA_PROBABILITY", 0.15)

# Порог "уверенности" ниже которого срабатывают инстинкты, а не кортекс
CONFIDENCE_FALLBACK_THRESHOLD = _get_float("CONFIDENCE_FALLBACK_THRESHOLD", 0.4)


# --------------------------------------------------------------------------
# BLENDED MIMICRY — реалистичное смешение лепета и эхолалии (без резких
# переключений между режимами), Итерация: переработка babbling/echolalia.
# --------------------------------------------------------------------------
# Ширина "зоны смешения" вокруг BABBLING_VOCABULARY_THRESHOLD, в которой
# доля лепета в ответе плавно убывает от 1.0 до 0.0 (вместо жёсткого
# порога should_babble()).
MIMICRY_BLEND_WIDTH = _get_float("MIMICRY_BLEND_WIDTH", 15.0)
# Насколько сильно перегрузка стрессом "откатывает" к лепету даже при
# большом словаре — регрессия под стрессом, как у настоящих детей.
STRESS_REGRESSION_BABBLE_BONUS = _get_float("STRESS_REGRESSION_BABBLE_BONUS", 0.4)
# Максимальная доля слов входящей фразы юзера, которые попадают в
# смешанный ответ как "эхо" (реально повторённые слова, а не лепет).
BLENDED_ECHO_WORD_RATIO = _get_float("BLENDED_ECHO_WORD_RATIO", 0.5)

# --------------------------------------------------------------------------
# ОДНОСЛОВНАЯ СТАДИЯ — сколько СВОИХ (освоенных) слов организм произносит
# за одну реплику, пока не перешёл к полноценным фразам.
#
# Раньше этой стадии не существовало вовсе: код прыгал от чистого лепета
# сразу к предложениям от LLM. При словаре в 7 слов доля лепета выходила
# ровно 1.0, эхо отключалось целиком, и на "привет" бот отвечал случайными
# слогами — хотя знал слово "привет" лучше всех остальных. Теперь узнанные
# во входящей фразе освоенные слова произносятся, а лепет добирает
# незнакомое, как у ребёнка на однословной стадии.
#
# 3 — телеграфная речь ("привет как дела"), но не полноценная фраза:
# грамматики у организма на этом этапе ещё нет.
# --------------------------------------------------------------------------
MIMICRY_MAX_KNOWN_WORDS = _get_int("MIMICRY_MAX_KNOWN_WORDS", 3)


# --------------------------------------------------------------------------
# ИССЛЕДОВАНИЕ — попытка произнести ещё не освоенное слово.
#
# До сих пор такого механизма не было ВООБЩЕ: организм только эксплуатировал
# уже выученное, а всё незнакомое превращал в лепет. Чисто эксплуатирующая
# система не развивается — она сходится к тому, что уже умеет, и застывает.
#
# Пробуются только слова из зоны ближайшего развития (услышанные, но не
# закреплённые), а не совсем незнакомые: попытка далеко за пределами
# компетенции провалится и ничему не научит.
#
# Это ЕДИНСТВЕННЫЙ потребитель curiosity, и он не дублирует другие сигналы.
# Настроение уникально тем, что несёт инерцию: сырые сигналы говорят о
# текущем событии, а любопытство переносится через ходы. Поэтому склонность
# рискнуть определяется накопленным состоянием, а не отдельной репликой.
#
# Замыкает контур освоения: попробовал -> похвалили -> закрепилось. Узел
# опробованного слова уходит в used_node_ids, поэтому подкрепление до него
# доходит.
# --------------------------------------------------------------------------
# Базовая склонность рискнуть даже в спокойном состоянии: полностью
# нелюбопытный организм всё равно изредка пробует новое.
EXPLORATION_BASE_PROBABILITY = _get_float("EXPLORATION_BASE_PROBABILITY", 0.05)
# Вклад любопытства СВЕРХ базового уровня покоя (MOOD_BASELINE_CURIOSITY).
# При максимальном любопытстве даёт примерно каждую вторую попытку.
EXPLORATION_CURIOSITY_GAIN = _get_float("EXPLORATION_CURIOSITY_GAIN", 0.45)


# ==========================================================================
# 7. LOGGING
# ==========================================================================
LOG_LEVEL = _get_str("LOG_LEVEL", "INFO")



# ==========================================================================
# 8. MEMORY SEARCH — семантический / ключевой поиск по графу памяти
# ==========================================================================
# --------------------------------------------------------------------------
# СЕМАНТИЧЕСКИЙ ПОИСК — память ищет по СМЫСЛУ, а не по буквам.
#
# Раньше сходство считалось как keyword-пересечение плюс SequenceMatcher,
# и это давало абсурд. Замер на реальном узле "у меня есть кошка":
#     "у меня есть кот"              -> 0.870
#     "расскажи про кота"            -> не найдено
#     "мой домашний питомец мяукает" -> не найдено
#     "у меня есть кожа"             -> 0.884  <- ПОБЕЖДАЛА "кота"
# То есть слово, отличающееся одной буквой, было "релевантнее" синонима.
#
# Модель выбрана под ЖЕЛЕЗО: sentence-transformers тянет torch (~2.5 ГБ на
# диске, 0.5-1 ГБ RAM на процесс), а на этой машине 3.7 ГБ всего и рядом
# работают ещё три сервиса. navec — статические русские векторы: 51 МБ,
# ~370 МБ RAM, без torch. С отбрасыванием служебных слов даёт правильный
# порядок: кот 0.671, про кота 0.467, питомец мяукает 0.339, кожа 0.222.
#
# Всё необязательно: нет модели или библиотеки -> поиск молча остаётся
# строковым (см. services/embeddings.py).
# --------------------------------------------------------------------------
EMBEDDINGS_ENABLED = _get_str("EMBEDDINGS_ENABLED", "true").lower() == "true"
EMBEDDING_MODEL_PATH = _get_str(
    "EMBEDDING_MODEL_PATH",
    str(Path(MODELS_DIR) / "navec_hudlit_v1_12B_500K_300d_100q.tar"),
)
# Размерность модели — нужна для проверки целостности сохранённых BLOB-ов


# Порог итоговой комбинированной оценки схожести (0.0..1.0), при которой
# найденный узел памяти считается MEMORY HIT и подмешивается в контекст Cortex.
MEMORY_SEARCH_THRESHOLD = _get_float("MEMORY_SEARCH_THRESHOLD", 0.3)

# Вес компонента "пересечение ключевых слов" в итоговой оценке схожести
MEMORY_KEYWORD_WEIGHT = _get_float("MEMORY_KEYWORD_WEIGHT", 0.3)

# Вес компонента "нечёткое строковое сходство" (SequenceMatcher) в оценке
# Понижен с 0.4: нечёткое сравнение ЦЕЛЫХ строк награждает за общие
# служебные слова, и именно оно давало абсурд "кожа релевантнее кота".
# Совсем убирать нельзя — оно ловит опечатки и словоформы, которых нет в
# векторной модели. Замер на узле "у меня есть кошка":
#     0.2 -> кожа 0.629 (выше порога уверенного совпадения 0.55)
#     0.1 -> кожа 0.538 (честно помечается "вспомнилось смутно"), кот 0.710
#     0.0 -> имена собственные держатся только на keyword
MEMORY_FUZZY_WEIGHT = _get_float("MEMORY_FUZZY_WEIGHT", 0.1)

# Вес семантической близости. Наибольший из трёх: смысл важнее
# написания. Строковые составляющие оставлены не для симметрии —
# они ловят то, чего нет в векторной модели: имена собственные,
# редкие термины, выдуманные слова самого организма.
MEMORY_SEMANTIC_WEIGHT = _get_float("MEMORY_SEMANTIC_WEIGHT", 0.5)

# Насколько сильно текущий вес узла (сила памяти) влияет на итоговый ранкинг
# при выборе лучшего совпадения (небольшой tie-breaker в пользу "сильных" воспоминаний)
MEMORY_WEIGHT_INFLUENCE = _get_float("MEMORY_WEIGHT_INFLUENCE", 0.15)

# Минимальная длина слова, чтобы считаться "значимым" ключевым словом
# (отсекаем короткие союзы/предлоги без спискастоп-слов)
MEMORY_MIN_KEYWORD_LENGTH = _get_int("MEMORY_MIN_KEYWORD_LENGTH", 3)

# Порог уверенности (similarity), выше которого MEMORY_HIT считается
