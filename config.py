# --------------------------------------------------------------------------
# ОШИБКА ПРЕДСКАЗАНИЯ НАГРАДЫ (дофаминовый сигнал)
#
# Раньше подкрепление работало "задним числом": пришла похвала — усилили
# участвовавший узел. Это память о награде, но не СТРЕМЛЕНИЕ к ней:
# организм не выбирал поведение, которое раньше одобряли.
#
# Ключевая поправка, без которой конструкция вырождается: дофамин
# выделяется не на награду, а на НЕОЖИДАННУЮ награду —
#     rpe = фактическая_валентность - ожидаемая_для_этого_узла
# Наивное "стремиться к одобрению" схлопнулось бы мгновенно: организм
# нашёл бы одно слово, которое всегда хвалят, и долбил его вечно. С
# ошибкой предсказания то, что хвалят ВСЕГДА, перестаёт давать сигнал, и
# организм идёт пробовать новое — ровно поэтому ребёнок бросает освоенное
# слово и лезет за следующим.
#
# Одна и та же величина управляет двумя эффектами:
#   1. выбором слов (узлы с высоким ожиданием предпочитаются при равной
#      освоенности) — см. MemoryGraph.get_mastered_words_in;
#   2. темпом закрепления (|rpe| масштабирует boost/penalty) — дофамин
#      модулирует синаптическую пластичность, и ожидаемая награда почти
#      не ускоряет обучение.
#
# Симметрично уже сделанному восприятию: там ошибка предсказания входа
# (compute_surprise), здесь — ошибка предсказания награды.
# --------------------------------------------------------------------------
# Скорость обновления ожидания (альфа в правиле Рескорлы-Вагнера).
# 0.3 — примерно 5-6 согласованных оценок до насыщения ожидания.
REWARD_EXPECTATION_LEARNING_RATE = _get_float("REWARD_EXPECTATION_LEARNING_RATE", 0.3)

# Насколько сильно ожидание награды смещает выбор слова при прочих равных.
# Держится небольшим: освоенность (вес) должна оставаться главным
# критерием, иначе организм начнёт говорить редкими, но однажды
# похваленными словами вместо тех, которыми реально владеет.
REWARD_PREFERENCE_WEIGHT = _get_float("REWARD_PREFERENCE_WEIGHT", 0.35)

# Нижняя граница множителя темпа закрепления. Полностью ожидаемая награда
# (rpe около нуля) не должна обнулять обучение совсем — иначе узел
# перестал бы получать даже поддерживающее подкрепление.
REWARD_MIN_LEARNING_SCALE = _get_float("REWARD_MIN_LEARNING_SCALE", 0.15)


# --------------------------------------------------------------------------
# РАЗРЕШЕНИЕ ПРОТИВОРЕЧИЙ — вытеснение устаревшего новым.
#
# Без него память копила взаимоисключающие факты и отдавала случайный:
# "мою собаку зовут Рекс", через месяц "мою собаку зовут Бобик" — оба узла
# равноправны, причём УСТАРЕВШИЙ находился ЛУЧШЕ (0.906 против 0.875),
# потому что порядок выдачи решает сходство строк, а не время.
#
# УСТАРЕВШЕЕ ОСЛАБЛЯЕТСЯ, А НЕ УДАЛЯЕТСЯ. Это принципиально и согласуется
# со всей архитектурой: узел теряет стабильность и снова становится
# забываемым, но если факт на самом деле остался верным, пользователь
# упомянет его снова и узел восстановится. Поэтому ложное срабатывание
# стоит дёшево, а удаление было бы необратимым.
#
# Признак вытеснения: высокая СЕМАНТИЧЕСКАЯ близость (речь об одном и том
# же) при НЕПОЛНОМ словесном совпадении (значит не повтор, а другая
# версия). Чистый повтор словами совпадает и обязан просто подкреплять.
#
# ИЗВЕСТНОЕ ОГРАНИЧЕНИЕ, проверенное замером: на бессвязном входе детектор
# срабатывает лишнее. Стенд склеивает случайные фразы корпуса, и такие
# сообщения ("мы идём гулять один два три четыре пять") по всем
# поверхностным признакам неотличимы от поправки — проверены три:
#     семантическая близость   0.82-0.95 у ОБЕИХ групп
#     доля общих слов          0.50-0.75 у ОБЕИХ
#     сходство последовательности 0.57-0.79 против 0.67-0.90, перекрытие
# Фильтр по устойчивости цели разделял идеально (все ложные метили в узлы
# со стабильностью 1.0), но ВОЗВРАЩАЛ исходный баг: если противоречие не
# найдено, поправка не записывается вовсе, и немедленная правка снова
# терялась. Поэтому фильтра нет.
#
# Живой человек бессвязных склеек не пишет, а цена ложного срабатывания
# мала: узел ослабляется, а не удаляется, и восстанавливается при
# следующем упоминании.
# --------------------------------------------------------------------------
# Насколько близкими по смыслу должны быть узлы, чтобы считаться речью об
# одном и том же. Держится высоким: лучше пропустить противоречие, чем
