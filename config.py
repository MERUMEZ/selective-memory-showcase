# --------------------------------------------------------------------------
# ПРИВЯЗАННОСТЬ СНИЖАЕТ ПОРОГ ТЕРПЕНИЯ К МОЛЧАНИЮ.
#
# Порог скуки был константой: организм ждал одинаково независимо от того,
# сложилась ли у него связь с этим человеком. Но привязанность — это
# медленная переменная, накопленная за много тёплых обменов, и её
# естественное поведенческое следствие именно такое: чем ближе человек,
# тем хуже переносится его молчание.
#
# Второй потребитель настроения (первый — любопытство -> исследование), и
